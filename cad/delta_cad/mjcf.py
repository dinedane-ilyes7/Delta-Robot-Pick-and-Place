"""MuJoCo export: one mesh per body and colour (in the body frame), mass properties from the CAD,
hinge / ball / free joints, connect constraints at the platform balls, springs as spatial tendons,
motor actuators with the belt ratio and the rotor inertia as armature. Also writes bodies.json."""
import json
import math
import os

import numpy as np

from .dims import CFG, L2, TH_MAX, TH_MIN
from .lib import DENSITY, PRINT_FILL, RGB, combine_props, mass_props, place, tessellate, write_stl

PRINTED = {"petg_cf", "pla", "tpu"}
SPRING_K = 1200.0          # N/m, extension spring 5 OD x 0.6 wire (see parts list)
SPRING_PRELOAD = 12.0      # N at the installed length


def part_props(shape, material, mass_override):
    rho = DENSITY[material] * (PRINT_FILL if material in PRINTED else 1.0)
    m, c, I = mass_props(shape, rho)
    if mass_override is not None:
        if mass_override == 0.0:
            return None
        k = mass_override / m
        m, I = mass_override, I * k
    return m, c, I


def body_props(body):
    items = [p for p in (part_props(s, mat, ms) for _, s, _, mat, ms in body.parts) if p is not None]
    return combine_props(items)


def quat(M):
    """w x y z of the rotation part of a 4x4 matrix."""
    R = M[:3, :3]
    w = math.sqrt(max(0.0, 1 + R[0, 0] + R[1, 1] + R[2, 2])) / 2
    x = math.copysign(math.sqrt(max(0.0, 1 + R[0, 0] - R[1, 1] - R[2, 2])) / 2, R[2, 1] - R[1, 2])
    y = math.copysign(math.sqrt(max(0.0, 1 - R[0, 0] + R[1, 1] - R[2, 2])) / 2, R[0, 2] - R[2, 0])
    z = math.copysign(math.sqrt(max(0.0, 1 - R[0, 0] - R[1, 1] + R[2, 2])) / 2, R[1, 0] - R[0, 1])
    q = np.array([w, x, y, z])
    return q / np.linalg.norm(q)


def f(v, n=6):
    return " ".join(f"{x:.{n}g}" for x in np.atleast_1d(v))


def export(bodies, cell_items, out_dir, rotor_inertia_kgm2, springs):
    mesh_dir = os.path.join(out_dir, "meshes")
    os.makedirs(mesh_dir, exist_ok=True)
    assets, meshes_done = [], {}

    def mesh_group(key, parts, M=None):
        """Write one STL per colour for a list of (shape, colour); returns [(mesh_name, colour)]."""
        by_col = {}
        for shp, col in parts:
            by_col.setdefault(col, []).append(shp if M is None else place(shp, M))
        out = []
        for col, shapes in sorted(by_col.items()):
            base_name = f"{key}_{col}"
            if base_name not in meshes_done:
                meshes_done[base_name] = []
                chunk, nf, k = [], 0, 0
                tess = [tessellate(s, 0.08, 0.3) for s in shapes]
                for v, fc in tess + [(None, None)]:
                    if v is None or (nf + len(fc) > 150000 and chunk):
                        name = base_name if k == 0 else f"{base_name}_{k}"
                        write_stl(os.path.join(mesh_dir, name + ".stl"), chunk)
                        assets.append(f'    <mesh name="{name}" file="{name}.stl" scale="0.001 0.001 0.001"/>')
                        meshes_done[base_name].append(name)
                        chunk, nf, k = [], 0, k + 1
                    if v is not None and len(fc):
                        chunk.append((v, fc))
                        nf += len(fc)
            out += [(nm, col) for nm in meshes_done[base_name]]
        return out

    def geoms(mlist, indent):
        return "\n".join(f'{indent}<geom type="mesh" mesh="{m}" material="m_{c}"/>' for m, c in mlist)

    report = {"units": "SI (m, kg, kg m^2, rad)", "bodies": {}, "constraints": [], "tendons": []}
    sim = CFG["sim"]
    drive = CFG["drive"]
    ratio, eta = drive["ratio"], drive["belt_efficiency"]
    armature = rotor_inertia_kgm2 * ratio ** 2

    lines = [f'<mujoco model="delta_cell">',
             '  <!-- Generated by cad/build.py from the CAD. Do not edit by hand: change the CAD or robot.yaml and rebuild. -->',
             '  <compiler angle="radian" meshdir="meshes" inertiafromgeom="false" autolimits="true"/>',
             f'  <option timestep="{sim["timestep"]}" integrator="implicitfast" gravity="0 0 -9.81"/>',
             '  <size memory="64M"/>',
             '  <visual><global offwidth="1600" offheight="1200"/><quality shadowsize="4096"/></visual>',
             '  <default>',
             '    <geom contype="0" conaffinity="0" group="1"/>',
             '    <joint damping="0.0005"/>',
             f'    <equality solref="{f(sim["constraint_solref"])}"/>',
             '  </default>',
             '  <asset>',
             '    <texture name="grid" type="2d" builtin="checker" rgb1=".92 .92 .92" rgb2=".86 .86 .86" width="512" height="512"/>',
             '    <material name="floor" texture="grid" texrepeat="8 8"/>']
    for k, (r_, g_, b_) in RGB.items():
        a = 0.35 if k == "glass" else 1.0
        spec = 0.6 if k in ("alu", "alu_dark", "chrome", "steel", "brass", "spring") else 0.2
        lines.append(f'    <material name="m_{k}" rgba="{r_:.3f} {g_:.3f} {b_:.3f} {a}" specular="{spec}"/>')
    body_xml = []

    # ---------------- static: base (robot) + cell, in world coordinates
    base = bodies["base"]
    base_meshes = mesh_group("base", [(s, c) for _, s, c, _, _ in base.parts])
    cell_meshes = mesh_group("cell", [(s, c) for _, s, c, _, _ in cell_items]) if cell_items else []
    world = ['  <worldbody>',
             '    <light pos="0.3 -0.6 1.2" dir="-0.2 0.5 -1" diffuse=".8 .8 .8" castshadow="true"/>',
             '    <light pos="-0.5 0.5 1.0" dir="0.4 -0.4 -1" diffuse=".4 .4 .4" castshadow="false"/>',
             f'    <geom name="floor" type="plane" size="2 2 0.01" pos="0 0 {-0.367 - 0.016:.4f}" material="floor"/>',
             geoms(base_meshes, "    "), geoms(cell_meshes, "    ")]
    zb = CFG["cell"]["belt_z"]
    yc = CFG["cell"]["belt_centre_y"]
    xr = CFG["cell"]["belt_x_range"]
    world.append(f'    <!-- collision surface of the conveyor belt (moves in the sim by a slide of the caps) -->')
    world.append(f'    <geom name="belt_surface" type="box" size="{(xr[1] - xr[0]) / 2:.4f} {CFG["cell"]["belt_width"] / 2:.4f} 0.002" '
                 f'pos="{(xr[0] + xr[1]) / 2:.4f} {yc:.4f} {zb - 0.002:.4f}" contype="1" conaffinity="1" group="3" rgba="0 0 0 0"/>')

    # ---------------- arms and rods
    for n in (1, 2, 3):
        arm = bodies[f"arm{n}"]
        m, c, I = body_props(arm)
        M = arm.M
        pos, q = M[:3, 3] / 1000, quat(M)
        j = arm.joint
        am = mesh_group("arm", [(s, col) for _, s, col, _, _ in arm.parts])
        body_xml.append(f'    <body name="arm{n}" pos="{f(pos)}" quat="{f(q)}">')
        body_xml.append(f'      <joint name="j{n}" type="hinge" axis="0 1 0" ref="{math.radians(j["ref_deg"]):.6f}" '
                        f'range="{math.radians(TH_MIN):.5f} {math.radians(TH_MAX):.5f}" armature="{armature:.4g}" '
                        f'frictionloss="{drive["joint_friction"]}" damping="0.002"/>')
        body_xml.append(_inertial(m, c, I, "      "))
        body_xml.append(geoms(am, "      "))
        for sn, p in arm.sites.items():
            body_xml.append(f'      <site name="arm{n}_{sn}" pos="{f(p / 1000)}" size="0.003"/>')
        report["bodies"][f"arm{n}"] = dict(parent="world", pos=pos.tolist(), quat=q.tolist(),
                                          joint=dict(name=f"j{n}", type="hinge", axis_local=[0, 1, 0],
                                                     axis_world=M[:3, 1].tolist(), anchor_world=pos.tolist(),
                                                     ref=math.radians(j["ref_deg"]),
                                                     range=[math.radians(TH_MIN), math.radians(TH_MAX)],
                                                     armature=armature),
                                          mass=m / 1000, com=(c / 1000).tolist(), inertia=(I * 1e-9).tolist(),
                                          sites={k: (v / 1000).tolist() for k, v in arm.sites.items()})
        for ab in "ab":
            rod = bodies[f"rod{n}{ab}"]
            Mr = np.linalg.inv(M) @ rod.M
            m, c, I = body_props(rod)
            rm = mesh_group(f"rod_{ab}", [(s, col) for _, s, col, _, _ in rod.parts])
            body_xml.append(f'      <body name="rod{n}{ab}" pos="{f(Mr[:3, 3] / 1000)}" quat="{f(quat(Mr))}">')
            body_xml.append(f'        <joint name="ball{n}{ab}" type="ball" damping="0.0002" armature="2e-6"/>')
            body_xml.append(_inertial(m, c, I, "        "))
            body_xml.append(geoms(rm, "        "))
            for sn, p in rod.sites.items():
                body_xml.append(f'        <site name="rod{n}{ab}_{sn}" pos="{f(p / 1000)}" size="0.002"/>')
            body_xml.append('      </body>')
            report["bodies"][f"rod{n}{ab}"] = dict(parent=f"arm{n}", pos=(Mr[:3, 3] / 1000).tolist(), quat=quat(Mr).tolist(),
                                                  joint=dict(name=f"ball{n}{ab}", type="ball",
                                                             centre_world=(rod.M[:3, 3] / 1000).tolist()),
                                                  mass=m / 1000, com=(c / 1000).tolist(), inertia=(I * 1e-9).tolist(),
                                                  sites={k: (v / 1000).tolist() for k, v in rod.sites.items()})
        body_xml.append('    </body>')

    # ---------------- platform
    plat = bodies["platform"]
    m, c, I = body_props(plat)
    pm = mesh_group("platform", [(s, col) for _, s, col, _, _ in plat.parts])
    body_xml.append(f'    <body name="platform" pos="{f(plat.M[:3, 3] / 1000)}">')
    body_xml.append('      <freejoint name="platform_free"/>')
    body_xml.append(_inertial(m, c, I, "      "))
    body_xml.append(geoms(pm, "      "))
    for sn, p in plat.sites.items():
        body_xml.append(f'      <site name="platform_{sn}" pos="{f(p / 1000)}" size="0.003"/>')
    body_xml.append('    </body>')
    report["bodies"]["platform"] = dict(parent="world", pos=(plat.M[:3, 3] / 1000).tolist(), quat=[1, 0, 0, 0],
                                        joint=dict(name="platform_free", type="free"), mass=m / 1000,
                                        com=(c / 1000).tolist(), inertia=(I * 1e-9).tolist(),
                                        sites={k: (v / 1000).tolist() for k, v in plat.sites.items()})
    world += body_xml
    world.append('  </worldbody>')

    eq = ['  <equality>']
    for n in (1, 2, 3):
        for ab in "ab":
            eq.append(f'    <connect name="close{n}{ab}" body1="rod{n}{ab}" body2="platform" anchor="0 0 {L2 / 1000:.4f}"/>')
            report["constraints"].append(dict(type="connect", body1=f"rod{n}{ab}", body2="platform",
                                              anchor_body1=[0, 0, L2 / 1000], site_body2=f"ball_{n}{ab}"))
    eq.append('  </equality>')

    ten = ['  <tendon>']
    for name, p0, p1, _ in springs:
        n, end = name.split("_")[-2], name.split("_")[-1]
        L = float(np.linalg.norm(p1 - p0)) / 1000
        L0 = L - SPRING_PRELOAD / SPRING_K
        ten.append(f'    <spatial name="spring{n}_{end}" stiffness="{SPRING_K}" springlength="{L0:.5f}" damping="0.05" '
                   f'width="0.0025" rgba=".72 .73 .75 1">')
        ten.append(f'      <site site="rod{n}a_spring_{end}"/><site site="rod{n}b_spring_{end}"/>')
        ten.append('    </spatial>')
        report["tendons"].append(dict(name=f"spring{n}_{end}", sites=[f"rod{n}a_spring_{end}", f"rod{n}b_spring_{end}"],
                                      stiffness=SPRING_K, rest_length=L0, installed_length=L))
    ten.append('  </tendon>')

    tq = drive["motor"]["holding_torque"]
    act = ['  <actuator>',
           f'    <!-- ctrl = motor torque (N m); gear = belt ratio x efficiency. Swap for <position> to emulate a stiff stepper. -->']
    for n in (1, 2, 3):
        act.append(f'    <motor name="m{n}" joint="j{n}" gear="{ratio * eta:.3f}" ctrlrange="{-tq} {tq}"/>')
    act.append('  </actuator>')
    sen = ['  <sensor>']
    for n in (1, 2, 3):
        sen.append(f'    <jointpos name="enc{n}" joint="j{n}"/>')
        sen.append(f'    <jointvel name="vel{n}" joint="j{n}"/>')
    sen += ['    <framepos name="tcp_pos" objtype="site" objname="platform_tcp"/>',
            '    <framequat name="platform_quat" objtype="body" objname="platform"/>',
            '    <accelerometer name="imu_acc" site="platform_imu"/>',
            '    <gyro name="imu_gyro" site="platform_imu"/>',
            '  </sensor>']
    xml = "\n".join(lines + assets + ['  </asset>'] + world + eq + ten + act + sen + ['</mujoco>']) + "\n"
    path = os.path.join(out_dir, "delta_cell.xml")
    open(path, "w").write(xml)
    report["armature_note"] = f"rotor + 20T pulley inertia {rotor_inertia_kgm2:.3g} kg m^2 x ratio^2 = {armature:.3g}"
    json.dump(report, open(os.path.join(out_dir, "bodies.json"), "w"), indent=1)
    return path, report


def _inertial(m, c, I, ind):
    return (f'{ind}<inertial pos="{f(c / 1000)}" mass="{m / 1000:.6g}" '
            f'fullinertia="{I[0, 0] * 1e-9:.5g} {I[1, 1] * 1e-9:.5g} {I[2, 2] * 1e-9:.5g} '
            f'{I[0, 1] * 1e-9:.5g} {I[0, 2] * 1e-9:.5g} {I[1, 2] * 1e-9:.5g}"/>')
